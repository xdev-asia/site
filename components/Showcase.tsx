'use client';

import { useRef, useState, type KeyboardEvent } from 'react';

const HEADER = '<!-- Generated by xDev from the docs marked for agents. Edit those docs, not this file. -->';
const SECTIONS = `## Auth
_Source: \`auth.md\`_

Sessions last 14 days. Tokens rotate on every login.

## Billing
_Source: \`billing.md\`_

Invoices are issued on the 1st of each month, in the customer's currency.

- Tax is added per line, at the rate for the shipping country.
- A failed charge is retried 3 times over 5 days, then the account is paused.
- Refunds go back to the original card; see [[runbook]] for manual ones.`;

// Verbatim output of `xdev export docs` and `xdev check docs` on the sample repo.
const SHEETS = [
  { id: 'agents', name: 'AGENTS.md', from: 'xdev export docs', body: `${HEADER}\n# Agent guide\n\n${SECTIONS}` },
  { id: 'claude', name: 'CLAUDE.md', from: 'xdev export docs', body: `${HEADER}\n# Claude Code guide\n\n@AGENTS.md` },
  { id: 'gemini', name: 'GEMINI.md', from: 'xdev export docs', body: `${HEADER}\n# Gemini guide\n\n@AGENTS.md` },
  {
    id: 'cursor',
    name: '.cursor/rules/xdev.mdc',
    from: 'xdev export docs',
    body: `---\ndescription: Project context generated by xDev\nalwaysApply: true\n---\n${HEADER}\n# Cursor guide\n\n${SECTIONS}`,
  },
  { id: 'check', name: 'Terminal', from: 'Exits 1 when any doc is stale', body: '$ xdev check docs\nstale\tbilling.md\t1' },
];
const LABELS: Record<string, string> = { agents: 'AGENTS.md', claude: 'CLAUDE.md', gemini: 'GEMINI.md', cursor: 'xdev.mdc', check: 'xdev check' };

export default function Showcase() {
  const [active, setActive] = useState(0);
  const [swapping, setSwapping] = useState(false);
  const tabs = useRef<(HTMLButtonElement | null)[]>([]);
  const sheet = SHEETS[active];

  const select = (i: number) => {
    if (i === active) return;
    setSwapping(true);
    // Swap content while the sheet is faded out, so text never jumps in view.
    window.setTimeout(() => {
      setActive(i);
      setSwapping(false);
    }, 200);
  };

  const onKey = (e: KeyboardEvent, i: number) => {
    const step = e.key === 'ArrowDown' || e.key === 'ArrowRight' ? 1 : e.key === 'ArrowUp' || e.key === 'ArrowLeft' ? -1 : 0;
    if (!step) return;
    e.preventDefault();
    const n = (i + step + SHEETS.length) % SHEETS.length;
    tabs.current[n]?.focus();
    select(n);
  };

  return (
    <div className="grid">
      <div className="show-names">
        <h2 id="outputs-title" className="block-head" data-reveal>
          One doc in, four agent files out
        </h2>
        <div className="names" role="tablist" aria-label="Generated files" data-reveal>
          {SHEETS.map((s, i) => (
            <button
              key={s.id}
              ref={(el) => {
                tabs.current[i] = el;
              }}
              role="tab"
              id={`tab-${s.id}`}
              aria-selected={i === active}
              aria-controls="sheet"
              tabIndex={i === active ? 0 : -1}
              onClick={() => select(i)}
              onKeyDown={(e) => onKey(e, i)}
            >
              {LABELS[s.id]}
            </button>
          ))}
        </div>
      </div>
      <div className="show-stage">
        <article className={swapping ? 'sheet is-swapping' : 'sheet'} data-ui id="sheet" role="tabpanel" aria-labelledby={`tab-${sheet.id}`}>
          <div className="sheet-head">
            <strong>
              <code>{sheet.name}</code>
            </strong>
            <span className="note">{sheet.from}</span>
          </div>
          <pre>{sheet.body}</pre>
        </article>
      </div>
    </div>
  );
}
